from decimal import Decimal
from typing import Protocol, runtime_checkable

from app.exchange_execution.models import (
    ExchangeCommand,
    ExchangeOrderEventSource,
    ExchangeOrderStatus,
    ExchangeTrade,
    ExecutionSession,
)
from app.persistence.exchange_models import (
    DurableExchangeOrder,
    ExchangeExecutionRoot,
    ExchangeReconciliationState,
    ExecutionBootstrap,
    LocalExchangeRecoveryResult,
    PersistentExchangeReconciliationRun,
    TradeCompletenessStatus,
)
from app.persistence.models import (
    CycleOutcome,
    DurableDecisionState,
    InitialPortfolioRecord,
    PaperAttributionV1,
    PersistentCommandRecord,
    PersistentDecisionRecord,
    PersistentFillRecord,
    PortfolioCheckpoint,
    PortfolioState,
    PortfolioTransitionRecord,
    RecoveryResult,
)


@runtime_checkable
class PaperCycleTransaction(Protocol):
    def claim_decision(self, record: PersistentDecisionRecord) -> bool: ...
    def record_command(self, record: PersistentCommandRecord) -> bool: ...
    def record_fill(self, record: PersistentFillRecord) -> bool: ...
    def record_attribution(self, record: PaperAttributionV1) -> bool: ...
    def record_portfolio_transition(self, record: PortfolioTransitionRecord) -> int: ...
    def set_portfolio_current(self, state: PortfolioState, journal_seq: int) -> None: ...
    def mark_terminal(self, stable_decision_key: str, outcome: CycleOutcome) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


@runtime_checkable
class RecoveryView(Protocol):
    def load_initial(self, portfolio_id: str) -> InitialPortfolioRecord | None: ...
    def load_current(self, portfolio_id: str) -> PortfolioState | None: ...
    def load_checkpoints(self, portfolio_id: str) -> tuple[PortfolioCheckpoint, ...]: ...
    def load_transitions(self, portfolio_id: str) -> tuple[PortfolioTransitionRecord, ...]: ...
    def integrity_check(self) -> tuple[str, ...]: ...


@runtime_checkable
class TradingPersistence(RecoveryView, Protocol):
    def initialize_portfolio(self, record: InitialPortfolioRecord) -> bool: ...
    def begin_cycle(self) -> PaperCycleTransaction: ...
    def recover(self, portfolio_id: str) -> RecoveryResult: ...
    def load_terminal_decision(self, stable_decision_key: str) -> DurableDecisionState | None: ...
    def load_attribution(self, stable_decision_key: str) -> PaperAttributionV1 | None: ...
    def load_attributions(self) -> tuple[PaperAttributionV1, ...]: ...
    def load_fill(self, durable_command_key: str) -> PersistentFillRecord | None: ...
    def create_checkpoint(self, state: PortfolioState, journal_seq: int) -> bool: ...
    def rebuild_portfolio_current(self, state: PortfolioState, journal_seq: int) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class ExchangeLifecyclePersistence(Protocol):
    def initialize_execution(
        self, root: ExchangeExecutionRoot, session: ExecutionSession, *, audit_identifier: str
    ) -> ExecutionBootstrap: ...
    def prepare_order(
        self,
        *,
        execution_root_id: str,
        session_id: str,
        command: ExchangeCommand,
        client_order_id: str,
        occurred_at_ms: int,
    ) -> DurableExchangeOrder: ...
    def begin_submission(
        self, durable_command_key: str, *, occurred_at_ms: int
    ) -> DurableExchangeOrder: ...
    def record_status(
        self,
        durable_command_key: str,
        *,
        status: ExchangeOrderStatus,
        occurred_at_ms: int,
        reason_code: str,
        exchange_order_id: str | None = None,
        acknowledged_at_ms: int | None = None,
        cumulative_executed_base_quantity: Decimal | None = None,
        cumulative_quote_quantity: Decimal | None = None,
        exchange_timestamp_ms: int | None = None,
        source: ExchangeOrderEventSource = ExchangeOrderEventSource.TRANSPORT,
        count_failure: bool = False,
    ) -> DurableExchangeOrder: ...
    def persist_trades(
        self, durable_command_key: str, trades: tuple[ExchangeTrade, ...]
    ) -> tuple[ExchangeTrade, ...]: ...
    def load_order(self, durable_command_key: str) -> DurableExchangeOrder: ...
    def list_orders(self) -> tuple[DurableExchangeOrder, ...]: ...
    def trade_completeness(self, durable_command_key: str) -> TradeCompletenessStatus: ...
    def trade_count(self, durable_command_key: str) -> int: ...
    def read_reconciliation_state(self, execution_root_id: str) -> ExchangeReconciliationState: ...
    def record_reconciliation_run(
        self, record: PersistentExchangeReconciliationRun
    ) -> ExchangeReconciliationState: ...
    def recover_local(self) -> LocalExchangeRecoveryResult: ...
